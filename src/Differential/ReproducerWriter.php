<?php

declare(strict_types=1);

namespace Mgrunder\RedisClientTester\Differential;

/**
 * Preserves a divergence as:
 *
 *   <dir>/case.json          the exact generated testcase
 *   <dir>/metadata.json      environment, options, and divergence details
 *   <dir>/reproduce.php      standalone reproducer (minimized when possible)
 *   <dir>/minimized.json     the minimized testcase, when minimization helped
 *   <dir>/original.php       reproducer for the unminimized case, in that case
 *   <dir>/report.txt         the reproducer's output when the case was saved
 *
 * The reproducers embed {@see DiffRuntime} verbatim and hard-code the setup
 * and test sequences, so `php reproduce.php` needs nothing from this package.
 *
 * @phpstan-import-type Server from DiffRuntime
 */
final class ReproducerWriter
{
    public function __construct(private readonly string $root)
    {
    }

    public function root(): string
    {
        return rtrim($this->root, '/');
    }

    /**
     * A new, unused directory for a finding. Names are derived from the case,
     * with a numeric suffix rather than ever reusing an existing directory.
     */
    public function allocate(TestCase $case, string $category = ''): string
    {
        $base = rtrim($this->root, '/') . ($category === '' ? '' : '/' . $category);
        if (!is_dir($base) && !@mkdir($base, 0777, true) && !is_dir($base)) {
            throw new \RuntimeException("cannot create {$base}");
        }

        $name = sprintf('%08x', crc32($case->prefix . ':' . $case->seed));
        for ($suffix = 0; $suffix < 1000; $suffix++) {
            $dir = $base . '/' . $name . ($suffix === 0 ? '' : '-' . $suffix);
            if (@mkdir($dir, 0777)) {
                return $dir;
            }
        }

        throw new \RuntimeException("cannot allocate a reproducer directory under {$base}");
    }

    /**
     * @param Server $server
     * @param array<string, mixed> $metadata
     */
    public function write(string $dir, TestCase $original, ?TestCase $minimized, array $server, array $metadata): void
    {
        $this->put($dir . '/case.json', $original->toJson());
        if ($minimized !== null) {
            $this->put($dir . '/minimized.json', $minimized->toJson());
            $this->put($dir . '/original.php', self::source($original, $server, $metadata));
        }
        $this->put($dir . '/reproduce.php', self::source($minimized ?? $original, $server, $metadata));
        $this->put($dir . '/metadata.json', json_encode(
            $metadata,
            JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_INVALID_UTF8_SUBSTITUTE,
        ) . "\n");
    }

    public function writeReport(string $dir, string $report): void
    {
        $this->put($dir . '/report.txt', $report);
    }

    /**
     * Run a case the way its reproducer does and capture the report.
     *
     * @param Server $server
     * @return array{0: int, 1: string} Exit status and output.
     */
    public static function report(TestCase $case, array $server): array
    {
        ob_start();
        try {
            $status = DiffRuntime::main($case->runtime(), $server);
        } catch (\Throwable $throwable) {
            $status = 2;
            echo 'reproducer failed: ' . $throwable->getMessage() . "\n";
        } finally {
            $output = (string) ob_get_clean();
        }

        return [$status, $output];
    }

    /**
     * @param Server $server
     * @param array<string, mixed> $metadata
     */
    public static function source(TestCase $case, array $server, array $metadata = []): string
    {
        $header = [
            'Differential reproducer generated by redis-client-tester-diff.',
            '',
            'Runs identical setup and an identical command sequence through PhpRedis',
            'and Relay, starting from identical Redis state, and reports every command',
            'and the first difference in replies or resulting Redis state. Exits 1',
            'while the divergence still reproduces, 0 once it no longer does.',
            '',
            'Only keys beneath the prefix below are touched. Override the target with',
            'REDIS_HOST and REDIS_PORT, and the client order with',
            'DIFF_ORDER=phpredis,relay or DIFF_ORDER=relay,phpredis.',
            '',
            sprintf('seed %d, case %d', $case->seed, $case->index),
        ];
        foreach (['found', 'signature', 'summary', 'php', 'phpredis', 'relay', 'server'] as $field) {
            $value = $metadata[$field] ?? null;
            if (is_scalar($value)) {
                $header[] = $field . ': ' . str_replace(['*/', "\n"], ['* /', ' '], (string) $value);
            }
        }

        $caseLiteral = "[\n"
            . '    \'prefix\' => ' . PhpLiteral::export($case->prefix) . ",\n"
            . '    \'options\' => ' . PhpLiteral::export($case->options, 1) . ",\n"
            . '    \'order\' => ' . PhpLiteral::export($case->order, 1) . ",\n"
            . "    'setup' => [\n";
        foreach ($case->setup as $command) {
            $caseLiteral .= '        ' . PhpLiteral::export($command, 2) . ",\n";
        }
        $caseLiteral .= "    ],\n    'test' => [\n";
        foreach ($case->test as $index => $op) {
            $caseLiteral .= sprintf("        /* %d */ [%s, %s, %s],\n", $index, PhpLiteral::export($op[0]), PhpLiteral::export($op[1], 2), PhpLiteral::export($op[2]));
        }
        $caseLiteral .= "    ],\n]";

        $serverLiteral = PhpLiteral::export([
            'host' => $server['host'],
            'tls_options' => $server['tls_options'] ?? [],
            'port' => $server['port'],
            'timeout' => $server['timeout'],
            'read_timeout' => $server['read_timeout'],
            'auth' => $server['auth'],
            'ttl_tolerance_ms' => $server['ttl_tolerance_ms'],
            'strict_messages' => $server['strict_messages'],
        ], 0);

        return "<?php\n\n/*\n * " . implode("\n * ", array_map(static fn (string $line): string => rtrim($line), $header)) . "\n */\n\n"
            . '$server = ' . $serverLiteral . ";\n\n"
            . '$case = ' . $caseLiteral . ";\n\n"
            . "exit(DiffRuntime::main(\$case, \$server));\n\n"
            . self::runtimeSource();
    }

    /** The source of {@see DiffRuntime}, moved to the global namespace. */
    public static function runtimeSource(): string
    {
        $file = (new \ReflectionClass(DiffRuntime::class))->getFileName();
        $source = $file === false ? false : file_get_contents($file);
        if (!is_string($source)) {
            throw new \RuntimeException('cannot read the DiffRuntime source');
        }

        $source = (string) preg_replace('/\A<\?php\s*/', '', $source);
        $source = (string) preg_replace('/^namespace [^;]+;\n/m', '', $source, 1);

        return "// ---- DiffRuntime, embedded from redis-client-tester-diff ----\n\n" . ltrim($source);
    }

    private function put(string $path, string $contents): void
    {
        if (file_put_contents($path, $contents) === false) {
            throw new \RuntimeException("cannot write {$path}");
        }
    }
}
